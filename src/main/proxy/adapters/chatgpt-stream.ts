/**
 * ChatGPT Stream Response Handler
 * Converts ChatGPT SSE stream to OpenAI compatible format
 */

import { PassThrough } from 'stream'
import { parseToolCallsFromText } from '../utils/toolParser'
import {
  createToolCallState,
  processStreamContent,
  flushToolCallBuffer,
  createBaseChunk,
  ToolCallState
} from '../utils/streamToolHandler'
import type { ChatGPTAdapter } from './chatgpt'

interface ChatGPTSSEChunk {
  message?: {
    id: string
    role: string
    content: {
      content_type: string
      parts?: string[]
    }
  }
  error?: string
  conversation_id?: string
}

export class ChatGPTStreamHandler {
  private model: string
  private conversationId: string
  private messageId: string = ''
  private isFirstChunk: boolean = true
  private created: number
  private onEnd?: () => void
  private toolCallState: ToolCallState
  private adapter?: ChatGPTAdapter

  constructor(
    model: string,
    conversationId: string,
    onEnd?: () => void,
    adapter?: ChatGPTAdapter
  ) {
    this.model = model
    this.conversationId = conversationId
    this.created = Math.floor(Date.now() / 1000)
    this.onEnd = onEnd
    this.toolCallState = createToolCallState()
    this.adapter = adapter
  }

  private parseSSE(data: string): ChatGPTSSEChunk | null {
    try {
      return JSON.parse(data)
    } catch {
      return null
    }
  }

  private createChunk(delta: { role?: string; content?: string }, finishReason?: string): string {
    return `data: ${JSON.stringify({
      id: `${this.conversationId}@${this.messageId}`,
      model: this.model,
      object: 'chat.completion.chunk',
      choices: [{
        index: 0,
        delta,
        finish_reason: finishReason || null,
      }],
      created: this.created,
    })}\n\n`
  }

  async handleStream(stream: NodeJS.ReadableStream): Promise<NodeJS.ReadableStream> {
    const transStream = new PassThrough()
    let buffer = ''

    stream.on('data', (chunk: Buffer) => {
      buffer += chunk.toString()
      const lines = buffer.split('\n')
      buffer = lines.pop() || ''

      for (const line of lines) {
        if (!line.trim() || !line.startsWith('data: ')) continue

        const data = line.slice(6).trim()
        if (data === '[DONE]') {
          this.handleDone(transStream)
          return
        }

        const parsed = this.parseSSE(data)
        if (!parsed) continue

        this.processChunk(parsed, transStream)
      }
    })

    stream.on('end', () => {
      this.handleDone(transStream)
    })

    stream.on('error', (err) => {
      transStream.emit('error', err)
    })

    return transStream
  }

  private processChunk(chunk: ChatGPTSSEChunk, transStream: PassThrough): void {
    // Extract message ID
    if (chunk.message?.id && !this.messageId) {
      this.messageId = chunk.message.id
    }

    // Extract content from message
    const messageContent = chunk.message?.content
    if (!messageContent) return

    // Handle text content (most common case)
    if (messageContent.content_type === 'text' && messageContent.parts) {
      const content = messageContent.parts.join('')

      // Use tool call state processing for content
      const baseChunk = createBaseChunk(`${this.conversationId}@${this.messageId}`, this.model, this.created)
      const { chunks, shouldFlush } = processStreamContent(
        content,
        this.toolCallState,
        baseChunk,
        this.isFirstChunk,
        'chatgpt'
      )

      // Send any chunks generated by tool call processing
      for (const outChunk of chunks) {
        transStream.write(`data: ${JSON.stringify(outChunk)}\n\n`)
        this.isFirstChunk = false
      }

      // If we're buffering a tool call or already emitted tool calls, don't send as regular content
      if (this.toolCallState.isBufferingToolCall || this.toolCallState.hasEmittedToolCall) {
        return
      }

      // If no chunks were sent, send as regular delta
      if (chunks.length === 0 && content) {
        const delta: { role?: string; content?: string } = {}
        if (this.isFirstChunk) {
          delta.role = 'assistant'
        }
        delta.content = content

        transStream.write(this.createChunk(delta))
        this.isFirstChunk = false
      }
    }
  }

  private handleDone(transStream: PassThrough): void {
    // If we haven't sent the first chunk (role: assistant), send it now
    // This handles cases where the model doesn't send any content chunks
    if (this.isFirstChunk) {
      transStream.write(this.createChunk({ role: 'assistant' }))
    }

    // Flush tool call buffer before finishing
    const baseChunk = createBaseChunk(`${this.conversationId}@${this.messageId}`, this.model, this.created)
    const flushChunks = flushToolCallBuffer(this.toolCallState, baseChunk, 'chatgpt')
    for (const outChunk of flushChunks) {
      transStream.write(`data: ${JSON.stringify(outChunk)}\n\n`)
    }

    // Determine finish_reason based on whether we had tool calls
    const finishReason = this.toolCallState.hasEmittedToolCall ? 'tool_calls' : 'stop'

    transStream.write(this.createChunk({}, finishReason))
    transStream.write('data: [DONE]\n\n')
    transStream.end()

    // Call end callback
    this.onEnd?.()
  }

  async handleNonStream(stream: NodeJS.ReadableStream): Promise<any> {
    let accumulatedContent = ''
    let messageId = ''

    return new Promise((resolve, reject) => {
      let buffer = ''

      stream.on('data', (chunk: Buffer) => {
        buffer += chunk.toString()
        const lines = buffer.split('\n')
        buffer = lines.pop() || ''

        for (const line of lines) {
          if (!line.trim() || !line.startsWith('data: ')) continue

          const data = line.slice(6).trim()
          if (data === '[DONE]') return

          try {
            const parsed = this.parseSSE(data)
            if (!parsed) continue

            if (parsed.message?.id && !messageId) {
              messageId = parsed.message.id
              this.messageId = parsed.message.id
            }

            const messageContent = parsed.message?.content
            if (messageContent?.content_type === 'text' && messageContent.parts) {
              accumulatedContent += messageContent.parts.join('')
            }
          } catch {
            // Ignore parse errors
          }
        }
      })

      stream.on('end', () => {
        // Parse tool calls from accumulated content
        const { content: cleanContent, toolCalls } = parseToolCallsFromText(accumulatedContent)

        const message: any = {
          role: 'assistant',
          content: toolCalls.length > 0 ? null : cleanContent.trim(),
        }

        if (toolCalls.length > 0) {
          message.tool_calls = toolCalls
        }

        resolve({
          id: `${this.conversationId}@${messageId}`,
          model: this.model,
          object: 'chat.completion',
          choices: [{
            index: 0,
            message,
            finish_reason: toolCalls.length > 0 ? 'tool_calls' : 'stop',
          }],
          usage: { prompt_tokens: 1, completion_tokens: 1, total_tokens: 2 },
          created: this.created,
        })
      })

      stream.on('error', reject)
    })
  }
}

export default ChatGPTStreamHandler
